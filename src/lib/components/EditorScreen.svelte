      ...originalTrack,
      keyframes: originalTrack.keyframes.filter(
        (frame: Keyframe) => !frame.id.startsWith('ai-gen-')
      ),
      effects: originalTrack.effects.filter(
        (effect: EffectKeyframe) => !effect.id.startsWith('ai-gen-')
      ),
    };
    generationBaseTrack = baseTrack;
    manualTimesByChannel = new Map(
      baseTrack.channels.map((channel) => [
        channel.id,
        baseTrack.keyframes
          .filter((frame) => frame.channelId === channel.id)
          .map((frame) => frame.timestampMs)
          .toSorted((a, b) => a - b),
      ])
    );
    session.beginEdit('Pre-fill lighting track');
    session.updateEdit(generationBaseTrack);

    try {
      const started = await startKeyframeGeneration(session.item.itemId, options);
      generationJobId = started.jobId;
      await collectGeneration(started);
    } catch (error) {
      generationError = (error as Error).message || 'Could not start keyframe generation';
      generationBusy = false;
      if (generatedFrames.length) session.commitEdit();
      else session.cancelEdit();
    }
  }

  async function collectGeneration(initial: GenerationJob) {
    let update = initial;
    while (true) {
      generationProgress = update.progress;
      generationThroughMs = update.throughMs;
      if (update.keyframes.length) {
        const spacing = session.minSpacingMs;
        const incoming: Keyframe[] = [];
        for (const raw of update.keyframes) {
          const frame = generatedKeyframe(raw);
          const manualTimes = manualTimesByChannel.get(frame.channelId) ?? [];
          let low = 0;
          let high = manualTimes.length;
          while (low < high) {
            const mid = (low + high) >>> 1;
            if (manualTimes[mid] < frame.timestampMs) low = mid + 1;
            else high = mid;
          }
          const collidesWithManual =
            (manualTimes[low] != null &&
              Math.abs(manualTimes[low] - frame.timestampMs) < spacing) ||
            (manualTimes[low - 1] != null &&
              Math.abs(manualTimes[low - 1] - frame.timestampMs) < spacing);
          const previousGenerated = lastGeneratedByChannel.get(frame.channelId);
          if (
            collidesWithManual ||
            (previousGenerated != null && frame.timestampMs - previousGenerated < spacing)
          )
            continue;
          incoming.push(frame);
          lastGeneratedByChannel.set(frame.channelId, frame.timestampMs);
        }
        generatedFrames = [...generatedFrames, ...incoming];
      }
      if (update.effects) {
        generatedEffects = update.effects
          .map(generatedEffect)
          .filter((effect): effect is EffectKeyframe => effect != null);
      }
      if (update.keyframes.length || update.effects) {
        const merged = {
          ...generationBaseTrack!,
          keyframes: [...generationBaseTrack!.keyframes, ...generatedFrames],
          effects: [...generationBaseTrack!.effects, ...generatedEffects],
        };
        session.updateEdit({ ...merged, safety: computeSafety(merged) });
      }
      if (update.throughMs > session.playheadMs + 250) session.seek(update.throughMs);
      generationSequence = update.sequence;
      if (update.state === 'done') {
        if (generatedFrames.length || generatedEffects.length) session.commitEdit();
        else session.cancelEdit();
        session.reloadSceneCuts();
        generationBusy = false;
        generationOpen = false;
        session.status =
          generatedFrames.length || generatedEffects.length
            ? `Generated ${generatedFrames.length} keyframes and ${generatedEffects.length} effects`
            : 'No new keyframes were generated; existing track content was kept';
        return;
      }
      if (update.state === 'failed') {
        generationError = update.error || 'Keyframe generation failed';
        if (generatedFrames.length || generatedEffects.length) session.commitEdit();
        else session.cancelEdit();
        generationBusy = false;
        return;
      }
      await new Promise((resolve) => window.setTimeout(resolve, 400));
      update = await fetchKeyframeGeneration(generationJobId, generationSequence);
    }
  }

